ok("device helper creates port 3000 reverse", "reverse tcp:3000 tcp:3000" in helper)
ok("device helper verifies reverse mapping", "reverse --list" in helper)
ok("R06 acceptance prepares device tunnel after SDK resolution", "VC-ANDROID-LOCAL-DEVICE-BACKEND.cmd" in accept and accept.index("VC-ANDROID-SDK-ENV.cmd") < accept.index("VC-ANDROID-LOCAL-DEVICE-BACKEND.cmd"))
ok("R06 acceptance retains compile gates", all(x in accept for x in [":app:compileDebugKotlin",":app:compileStagingKotlin",":app:compileReleaseKotlin"]))
